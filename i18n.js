function t(lang, key, args) {
    var table = STRINGS[lang] || STRINGS.en;
    var text = (key in table) ? table[key] : STRINGS.en[key];
    if (text === undefined) return key;

    if (args) {
        for (var name in args)
            text = text.replace("{" + name + "}", args[name]);
    }
    return text;
}

// Whether the string exists at all: per-provider hints built from an id
// ("loginHint.<registry id>") may legitimately be missing — the caller then
// shows a generic line instead of the key name itself.
function has(lang, key) {
    var table = STRINGS[lang] || STRINGS.en;
    return (key in table) || (key in STRINGS.en);
}
